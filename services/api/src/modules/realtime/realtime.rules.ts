/**
 * 实时通道的**纯规则**（M10 交付五 / F10-08）。
 *
 * ## 这一层解决什么
 *
 * 用户 2026-10-16：「我需要的是实时通知，我这边上传了打卡，另一台同家庭的设备要**立马**收到」。
 *
 * 在此之前"家里人刚做的事"一共有三条路能到另一台设备，但**最慢的那条是前台**：
 *
 * | 路子 | 延迟 |
 * | --- | --- |
 * | 应用前台 | **60 秒**（`staleTime`，或用户手动下拉） |
 * | 本机闹钟（交付二） | 只有"到点做饭/东西到期"两类 |
 * | 后台巡查（交付三） | 最多约 15 分钟（系统调度器的下限） |
 *
 * 也就是说：**两台手机都开着的场景，反而是最慢的**——它要等一次 60 秒的缓存过期。
 * 这一层补的就是这一段：应用开着时，服务端有变动**当场推**到那台设备上（毫秒级）。
 *
 * ## 为什么不引消息队列
 *
 * 用户提了"你不行就上消息队列吧"。要说清楚为什么这里不需要它：
 *
 * - **MQ 解决的是"服务端多实例之间怎么把消息送到持有连接的那一台"**，
 *   不解决"最后一段怎么到手机"。现在后端是**单实例**（`docker-compose.yml` 里一个 api 容器），
 *   进程内直接扇出就是最短路径，中间加一个 broker 只是多一跳、多一个要运维的东西；
 * - 真要多实例时，要改的**只是 `RealtimeService` 这一个类**：`signal()` 里加一次
 *   Redis pub/sub 的 publish，各实例订阅后推给本机连接。调用方（业务侧）一行都不用动
 *   ——所以现在这版已经为那天留好了位置，只是不提前引入。
 *
 * ## 为什么是 WebSocket 而不是 SSE
 *
 * 两条都能用，选 WebSocket 的具体理由是**原生那一侧**：Android 的 OkHttp 自带
 * `newWebSocket()`（前台服务要用它），而 SSE 在 Android 上得额外引 `okhttp-sse`
 * 或者自己解析事件流。一条协议两头都用得上，就它了。
 */

/** 通道挂在这个路径上（复用 HTTP 那个端口与 server，**不新开端口**） */
export const REALTIME_PATH = '/api/realtime'

/**
 * 心跳间隔。
 *
 * 目的是**认得出死连接**：手机进电梯、切到飞行模式时，TCP 对端不会立刻知道，
 * 那条连接会一直挂在表里（占着名额、发出去的消息石沉大海）。
 * 30 秒一次 ping，一轮不回就掐掉。
 *
 * 这是与手机网络现实的一个折中：更短会让手机频繁被唤醒（费电），
 * 更长则"对方早就没了"要一分钟以上才发现。
 */
export const HEARTBEAT_MS = 30_000

/**
 * 一个账号最多同时开几条连接。
 *
 * **不是安全边界，是防跑飞**：换账号、页面反复重载、写错的重连循环都可能留下僵尸连接。
 * 真要恶意占用，开满 5 条再开新的也只是把最旧那条挤掉，仍然占着 5 条不变——
 * 所以它的作用是"让连接数有界"，不是"防攻击"（那件事归 nginx/防火墙）。
 */
export const MAX_CONNECTIONS_PER_USER = 5

/**
 * 要不要接受这个来源（浏览器会带 `Origin`，原生客户端不带）。
 *
 * 与 HTTP 侧的 CORS 同一条口径（`CORS_ORIGIN` 环境变量）：
 * - **没有 `Origin` → 放行**：Android 的 OkHttp 默认不带这个头，而它拿的是巡查令牌
 *   （那本身就是凭据），所以"没有 Origin"不等于"可以随便连"；
 * - 配了白名单就按白名单；配成 `*`（或没配）表示都行——本机开发与单机部署就是这个状态。
 */
export function originAllowed(origin: string | undefined, allowed: string[]): boolean {
  if (!origin) return true
  if (allowed.includes('*')) return true
  return allowed.includes(origin)
}
